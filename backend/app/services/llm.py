def single_design_plan(raw, variant):
    """One variant's plan; a full three-plan answer is accepted and narrowed to that variant."""
    if isinstance(raw,dict) and 'slides' not in raw and isinstance(raw.get(variant),(dict,list)):
        raw=raw[variant]
    return normalize_design_plans({variant:raw})[variant]


def normalize_design_plans(raw):
    """Accept only lossless shorthand; Pydantic still validates every choice."""
    if not isinstance(raw, dict): return raw
    result = dict(raw)
    for key in ('a', 'b', 'c'):
        plan = result.get(key)
        if isinstance(plan, list): plan = {'slides': plan}
        if isinstance(plan, dict) and isinstance(plan.get('slides'), list):
            choices = []
            for choice in plan['slides']:
                if isinstance(choice, dict) and 'design' not in choice and set(choice) <= {'slide','composition','density','layout_shift','smartart'}:
                    choice = {'slide': choice.get('slide'), 'design': {k:v for k,v in choice.items() if k != 'slide'}}
                choices.append(choice)
            plan = {**plan, 'slides': choices}
        result[key] = plan
    return result

def configured() -> bool:
    host=urlparse(settings.base_url).hostname
    return bool(settings.base_url and settings.model and (settings.api_key or host in {'localhost','127.0.0.1','::1'}))

async def complete_json(system: str, payload: dict, client: httpx.AsyncClient | None = None,
                        images: list[str] | None = None, max_tokens: int | None = None) -> dict:
    if not configured(): raise LLMError('Заполните LLM_API_KEY и LLM_MODEL в backend/.env.')
    parsed=urlparse(settings.base_url)
    if parsed.scheme not in {'http','https'} or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise LLMError('LLM_BASE_URL должен быть HTTP(S)-адресом API без ключей в URL.')
    if parsed.scheme=='http' and parsed.hostname not in {'localhost','127.0.0.1','::1'}:
        raise LLMError('Для внешнего сервера модели требуется HTTPS, чтобы защитить ключ и материалы.')
    headers={'Content-Type':'application/json'}
    if settings.api_key:
        headers['Authorization']='Bearer '+settings.api_key
    if settings.project_id:
        headers['Project-ID']=settings.project_id
    task=payload.get('schema',{}).get('title')
    tokens={'DeckContent':settings.outline_max_tokens,'SlideRepair':settings.outline_max_tokens,'ThreeDesignPlans':settings.design_max_tokens,
            'DesignPlan':settings.design_max_tokens,'AssistantPlan':settings.assistant_max_tokens}.get(task,
            settings.audit_max_tokens if 'source_chunks' in payload else settings.max_tokens)
    if max_tokens is not None:
        tokens=max(tokens,max_tokens)
    body={**inference_options(),'model':settings.model,'temperature':settings.temperature,'max_tokens':tokens,
          'messages':[{'role':'system','content':system},{'role':'user','content':json.dumps(payload,ensure_ascii=False)}]}
    if images and settings.vision:
        body['messages'][-1]['content'] = [{'type':'text','text':body['messages'][-1]['content']},
            *[{'type':'image_url','image_url':{'url':data}} for data in images[:4]]]
    # Only add response_format if explicitly enabled and supported by provider
    if settings.json_mode and 'platformpreview' not in settings.base_url:
        body['response_format']={'type':'json_object'}
    client=client or provider_http.get()
    owned=client is None
    client=client or httpx.AsyncClient(timeout=httpx.Timeout(settings.timeout,connect=15),follow_redirects=False)
    started=monotonic()
    try:
        # HTTP read timeouts reset on each chunk; this also bounds trickling responses.
        async with asyncio.timeout(settings.timeout):
            for attempt in range(2):
                try:
                    response=await client.post(settings.base_url+'/chat/completions',headers=headers,json=body,
                                               timeout=httpx.Timeout(settings.timeout,connect=15,pool=15))
                    break
                except (httpx.RemoteProtocolError,httpx.ReadError,httpx.ConnectError) as exc:
                    # Provider gateways drop long generations without any response; one
                    # resend within the same time budget is safe because nothing was returned.
                    if attempt: raise
                    logging.getLogger(__name__).warning('LLM task=%s connection dropped after %.1fs (%s); retrying once',
                                                        task or 'audit',monotonic()-started,type(exc).__name__)
                    await asyncio.sleep(1)
        if response.status_code in {401,403}: raise LLMError('Провайдер отклонил ключ или доступ к модели. Проверьте .env.')
        if response.status_code==429: raise LLMError('Провайдер ограничил запросы. Повторите позже.')
        if response.status_code>=400:
            detail = ''
            try:
                provider_error = response.json().get('error', {}).get('message', '')
                if isinstance(provider_error, str):
                    if settings.api_key: provider_error = provider_error.replace(settings.api_key, '[redacted]')
                    detail = re.sub(r'[^\w\s.,:/-]', '', provider_error)[:180]
            except (ValueError, AttributeError):
                pass
            suffix = f' Причина провайдера: {detail}.' if detail else ''
            raise LLMError(f'Провайдер вернул HTTP {response.status_code}.{suffix} Проверьте model URI, URL и LLM_JSON_MODE.')
        data=response.json()
        choice=data['choices'][0]
        usage=data.get('usage') or {}
        logging.getLogger(__name__).info('LLM task=%s duration=%.3fs finish=%s prompt_tokens=%s completion_tokens=%s reasoning_tokens=%s',
            task or 'audit',monotonic()-started,choice.get('finish_reason'),usage.get('prompt_tokens'),usage.get('completion_tokens'),
            (usage.get('completion_tokens_details') or {}).get('reasoning_tokens'))
        if choice.get('finish_reason') in {'length','max_tokens'}:
            raise LLMTruncatedError('Ответ провайдера обрезан лимитом токенов вывода.')
        text=choice['message']['content']
        if not isinstance(text,str): raise ValueError('Нет текстового ответа')
        return extract_json(text)
    except LLMTruncatedError:
        raise
    except (TimeoutError, httpx.TimeoutException) as exc: raise LLMError('Модель не завершила ответ в пределах лимита времени. Уменьшите объём запроса или повторите позже.') from exc
    except httpx.HTTPError as exc: raise LLMError('Не удалось подключиться к LLM. Проверьте адрес сервера модели.') from exc
    except (ValueError,KeyError,IndexError,TypeError) as exc: raise LLMFormatError('Ответ модели не соответствует формату JSON. Проверьте поддержку JSON у провайдера.') from exc
    finally:
        if owned: await client.aclose()

async def complete_with_template(system, payload, template, max_tokens: int | None = None):
    token_budget={'max_tokens':max_tokens} if max_tokens is not None else {}
    if settings.vision:
        return await complete_json(system, payload, images=template_images(template),**token_budget)
    return await complete_json(system, payload,**token_budget)

